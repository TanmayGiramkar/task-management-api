-- Refresh tokens are random opaque strings handed to the client once. Only their SHA-256 hash is
-- stored, so someone who reads this table cannot use the tokens.
-- family_id is shared by every token rotated from the same login; reusing an already-rotated token
-- revokes the whole family (reuse detection).
-- Expiry times are TIMESTAMPTZ (mapped to java.time.Instant): an exact point in time, independent of
-- the server's time zone.
CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    family_id  UUID        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT refresh_tokens_token_hash_unique UNIQUE (token_hash)
);
