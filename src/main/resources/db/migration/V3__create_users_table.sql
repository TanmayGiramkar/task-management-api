-- Named "users" because "user" is a reserved word in PostgreSQL.
-- Emails are stored trimmed and lower-cased by the application, so the plain UNIQUE constraint
-- is enough to stop two accounts using the same address.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT users_email_unique UNIQUE (email)
);
